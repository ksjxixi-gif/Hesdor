#!/usr/bin/env node
// Regenerates the package-manager manifests in packaging/ for a published GitHub release:
//   node scripts/release/update-manifests.mjs [version] [--sums path/to/SHA256SUMS]
// version defaults to packages/cli/package.json; the hashes come from the release's SHA256SUMS
// (downloaded unless --sums is given). This file is the source of truth for every manifest below.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
export const REPO = 'ksjxixi-gif/Hesdor'
export const WINGET_ID = 'MohammadAbukhadija.Hesdor'
export const TARGETS = ['win-x64', 'linux-x64', 'linux-arm64', 'macos-arm64', 'macos-x64']
export const assetName = (target) => `hesdor-${target}${target.startsWith('win') ? '.zip' : '.tar.gz'}`
const DESCRIPTION = 'Local-first AI software engineering agent for the terminal'
const releaseUrl = (version) => `https://github.com/${REPO}/releases/download/v${version}`

/** Parses `sha256sum` output into { assetName: hash } and checks every target is present. */
export function parseSums(text) {
  const sums = {}
  for (const line of text.split(/\r?\n/)) {
    const m = /^([0-9a-f]{64})\s+\*?(\S+)$/i.exec(line.trim())
    if (m) sums[m[2]] = m[1].toLowerCase()
  }
  const missing = TARGETS.map(assetName).filter((a) => !sums[a])
  if (missing.length) throw new Error(`SHA256SUMS has no entry for: ${missing.join(', ')}`)
  return sums
}

/** Returns { relative path under packaging/: file content }. */
export function renderManifests(version, sums) {
  if (!/^\d+\.\d+\.\d+(-[\w.]+)?$/.test(version)) throw new Error(`not a version: ${version}`)
  const url = (t) => `${releaseUrl(version)}/${assetName(t)}`
  const sha = (t) => sums[assetName(t)]
  const generated = '# Generated by scripts/release/update-manifests.mjs; edit that script, not this file.'
  const schema = (type) => `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.1.12.0.schema.json`
  const winget = (file, type, body) => [`winget/${WINGET_ID}${file}.yaml`, `${generated}\n${schema(type)}\n\nPackageIdentifier: ${WINGET_ID}\nPackageVersion: ${version}\n${body}ManifestType: ${type}\nManifestVersion: 1.12.0\n`]

  return Object.fromEntries([
    winget('', 'version', 'DefaultLocale: en-US\n'),
    winget(
      '.installer',
      'installer',
      `InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
- RelativeFilePath: hesdor.exe
  PortableCommandAlias: hesdor
Commands:
- hesdor
Installers:
- Architecture: x64
  InstallerUrl: ${url('win-x64')}
  InstallerSha256: ${sha('win-x64').toUpperCase()}
`,
    ),
    winget(
      '.locale.en-US',
      'defaultLocale',
      `PackageLocale: en-US
Publisher: Mohammad Abukhadija
PublisherUrl: https://github.com/ksjxixi-gif
PublisherSupportUrl: https://github.com/${REPO}/issues
PackageName: Hesdor
PackageUrl: https://github.com/${REPO}
License: MIT
LicenseUrl: https://github.com/${REPO}/blob/main/LICENSE
ShortDescription: ${DESCRIPTION}
Moniker: hesdor
Tags:
- ai
- agent
- cli
- coding-assistant
- llm
ReleaseNotesUrl: https://github.com/${REPO}/releases/tag/v${version}
`,
    ),
    [
      'scoop/hesdor.json',
      JSON.stringify(
        {
          '##': 'Generated by scripts/release/update-manifests.mjs; edit that script, not this file.',
          version,
          description: DESCRIPTION,
          homepage: `https://github.com/${REPO}`,
          license: 'MIT',
          architecture: { '64bit': { url: url('win-x64'), hash: sha('win-x64') } },
          bin: 'hesdor.exe',
          checkver: 'github',
          autoupdate: {
            architecture: {
              '64bit': {
                url: `https://github.com/${REPO}/releases/download/v$version/${assetName('win-x64')}`,
                hash: { url: '$baseurl/SHA256SUMS', regex: '$sha256\\s+\\*?$basename' },
              },
            },
          },
        },
        null,
        2,
      ) + '\n',
    ],
    [
      'homebrew/hesdor.rb',
      `${generated}
# Copy to Formula/hesdor.rb in the ksjxixi-gif/homebrew-tap repository.
class Hesdor < Formula
  desc "${DESCRIPTION}"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${url('macos-arm64')}"
      sha256 "${sha('macos-arm64')}"
    end
    on_intel do
      url "${url('macos-x64')}"
      sha256 "${sha('macos-x64')}"
    end
  end

  on_linux do
    on_arm do
      url "${url('linux-arm64')}"
      sha256 "${sha('linux-arm64')}"
    end
    on_intel do
      url "${url('linux-x64')}"
      sha256 "${sha('linux-x64')}"
    end
  end

  def install
    bin.install "hesdor"
  end

  test do
    assert_equal "hesdor #{version}", shell_output("#{bin}/hesdor --version").strip
  end
end
`,
    ],
  ])
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2)
  const sumsAt = args.indexOf('--sums')
  const sumsFile = sumsAt >= 0 ? args.splice(sumsAt, 2)[1] : undefined
  const version = args[0]?.replace(/^v/, '') ?? JSON.parse(readFileSync(path.join(ROOT, 'packages/cli/package.json'), 'utf8')).version
  let text
  if (sumsFile) text = readFileSync(sumsFile, 'utf8')
  else {
    const res = await fetch(`${releaseUrl(version)}/SHA256SUMS`)
    if (!res.ok) throw new Error(`GET ${res.url}: ${res.status} (is v${version} released with binaries?)`)
    text = await res.text()
  }
  for (const [file, content] of Object.entries(renderManifests(version, parseSums(text)))) {
    const out = path.join(ROOT, 'packaging', file)
    mkdirSync(path.dirname(out), { recursive: true })
    writeFileSync(out, content)
    console.log(`wrote packaging/${file}`)
  }
}
